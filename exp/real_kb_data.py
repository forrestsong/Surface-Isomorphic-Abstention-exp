def q(e: str, a: str, tmpl: str) -> str:
    return TMPL[tmpl].format(e=e, a=a)


def all_items():
    """→ [{'id','entity','attr','gold'|None,'known_hint'}]。`known_hint` 只是我的预期，
    真正的切片由**测量**决定（见模块 docstring），不要用它当标签。"""
    out = []
    for e, attrs in ENTITIES.items():
        for a, g in attrs:
            out.append({"id": f"{e}::{a}", "entity": e, "attr": a, "gold": g,
                        "known_hint": g is not None})
    return out


def n_items():
    return sum(len(v) for v in ENTITIES.values())


